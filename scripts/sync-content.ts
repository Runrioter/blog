/**
 * Obsidian vault → SvelteKit content sync.
 *
 * Reads notes from the local Obsidian vault (content/, git-ignored) and
 * generates:
 *   - src/routes/(tutorials)/<section>/<name>/+page.svx  (mdsvex page)
 *   - src/routes/(tutorials)/<section>/toc.ts           (layout TOC list)
 *   - static/uploads/<section>/<image>                  (copied vault media)
 *
 * Notes:
 *   - Generated +page.svx files carry a marker comment and are the ONLY
 *     files this script may delete. Hand-written pages are never touched.
 *   - Run directly with Node >= 23.6 (type stripping): `node scripts/sync-content.ts`
 *   - `--watch` re-runs on vault changes.
 *
 * Vault conventions (keep your Obsidian setup minimal — core features only):
 *   - content/<section>/<name>.md  →  route /<section>/<name>/
 *   - [[wikilinks]] resolve by note basename and become relative links
 *   - ![[image.png]] (anywhere in the vault) is copied to static/uploads/<section>/
 *   - Callouts (> [!note] ...) degrade to plain blockquotes
 *   - Frontmatter: title (required), description, order (TOC sort)
 *   - Inline #tags and community-plugin syntax are NOT transformed — avoid them
 */

import {
	cpSync,
	existsSync,
	mkdirSync,
	readFileSync,
	readdirSync,
	rmSync,
	writeFileSync
} from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { headingSlug } from './heading-slug.js';

const VAULT_DIR = path.resolve(process.cwd(), 'content');
const ROUTES_DIR = path.resolve(process.cwd(), 'src', 'routes', '(tutorials)');
const UPLOADS_DIR = path.resolve(process.cwd(), 'static', 'uploads');
const MARKER =
	'<!-- GENERATED by `npm run content:sync` from the Obsidian vault (content/). Do not edit — edit the source note and re-run. -->';

type Note = {
	rel: string; // vault-relative path, e.g. `ai/basics.md`
	dir: string; // vault-relative dir, e.g. `ai` (or '' at vault root)
	name: string; // basename without extension, e.g. `basics`
	title: string;
	description: string;
	order: number;
	body: string;
};

type TransformError = { file: string; message: string };

const errors: TransformError[] = [];
const warnings: TransformError[] = [];
/** Vault notes carrying `publish: false` — they stay in the vault but never become routes. */
const skipped: string[] = [];

type TrailingSlash = 'ignore' | 'never' | 'always';

type SvelteConfig = {
	trailingSlash: TrailingSlash;
	slug: (text: string) => string;
};

// SvelteKit 3 keeps configuration in vite.config.ts; read trailingSlash from
// there. The slug function comes from the shared plain-JS module so this script
// never needs to execute the TypeScript Vite config.
function loadSvelteConfig(): Promise<SvelteConfig> {
	const configFile = new URL('../vite.config.ts', import.meta.url);
	const fallback: SvelteConfig = { trailingSlash: 'ignore', slug: headingSlug };
	return import(configFile.href).then(
		(mod) => ({
			trailingSlash: ((mod.default?.trailingSlash as string) || 'ignore') as TrailingSlash,
			slug: headingSlug
		}),
		() => fallback
	);
}

type Scalar = string | number | boolean;
type FrontmatterValue = Scalar | Scalar[];

function parseScalar(raw: string): Scalar {
	const value = raw.trim();
	if (/^".*"$/.test(value) || /^'.*'$/.test(value)) return value.slice(1, -1);
	else if (/^-?\d+$/.test(value)) return Number(value);
	else if (value === 'true' || value === 'false') return value === 'true';
	return value;
}

/** Split a comma-separated list, respecting single/double quotes (e.g. `a, "b, c"`, `'x'`). */
function splitList(raw: string): string[] {
	const parts: string[] = [];
	let current = '';
	let quote: string | null = null;
	for (const ch of raw) {
		if (quote) {
			if (ch === quote) quote = null;
			else current += ch;
		} else if (ch === '"' || ch === "'") {
			quote = ch;
		} else if (ch === ',') {
			parts.push(current.trim());
			current = '';
		} else {
			current += ch;
		}
	}
	const last = current.trim();
	if (last) parts.push(last);
	return parts.filter((p) => p !== '');
}

function parseFrontmatter(
	raw: string,
	file: string
): { meta: Record<string, FrontmatterValue>; body: string } {
	const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(raw);
	if (!match) return { meta: {}, body: raw };
	const meta: Record<string, FrontmatterValue> = {};
	const lines = match[1].split(/\r?\n/);
	for (let i = 0; i < lines.length; i++) {
		const line = lines[i];
		if (!line.trim() || line.trimStart().startsWith('#')) continue;

		// Block array: `key:` followed by indented `- item` lines.
		const block = /^([A-Za-z_][\w-]*):\s*$/.exec(line);
		if (block) {
			const items: Scalar[] = [];
			let j = i + 1;
			while (j < lines.length && /^\s+-\s+/.test(lines[j])) {
				items.push(parseScalar(lines[j].replace(/^\s+-\s+/, '')));
				j++;
			}
			if (items.length > 0) {
				meta[block[1]] = items;
				i = j - 1;
				continue;
			}
		}

		const kv = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(line);
		if (!kv) {
			warnings.push({ file, message: `ignoring unsupported frontmatter line: ${line.trim()}` });
			continue;
		}
		const rawValue = kv[2].trim();
		if (rawValue.startsWith('[') && rawValue.endsWith(']')) {
			// Inline array: `[a, "b c", 1, true]`; non-closed brackets stay a string.
			if (rawValue === '[]') meta[kv[1]] = [];
			else meta[kv[1]] = splitList(rawValue.slice(1, -1)).map(parseScalar);
		} else {
			meta[kv[1]] = parseScalar(rawValue);
		}
	}
	return { meta, body: raw.slice(match[0].length) };
}

function collectNotes(): Note[] {
	const notes: Note[] = [];
	if (!existsSync(VAULT_DIR)) return notes;
	const walk = (abs: string, rel: string): void => {
		for (const entry of readdirSync(abs, { withFileTypes: true })) {
			if (entry.name.startsWith('.')) continue;
			const entryRel = rel ? path.posix.join(rel, entry.name) : entry.name;
			const entryAbs = path.join(abs, entry.name);
			if (entry.isDirectory()) {
				walk(entryAbs, entryRel);
			} else if (entry.isFile() && entry.name.toLowerCase().endsWith('.md')) {
				const { meta, body } = parseFrontmatter(readFileSync(entryAbs, 'utf8'), entryRel + '.md');
				// `publish: false` keeps a vault-only note (e.g. the agent journal) in the
				// vault without generating a route for it.
				if (meta.publish === false) {
					skipped.push(entryRel);
					continue;
				}
				const title =
					typeof meta.title === 'string' ? meta.title : path.posix.basename(entryRel, '.md');
				const order = typeof meta.order === 'number' ? meta.order : 1000;
				notes.push({
					rel: entryRel,
					dir: path.posix.dirname(entryRel),
					name: path.posix.basename(entryRel, '.md'),
					title,
					description: typeof meta.description === 'string' ? meta.description : '',
					order,
					body: body.replace(/^\s+/, '')
				});
			}
		}
	};
	walk(VAULT_DIR, '');
	return notes;
}

function byName(notes: Note[]): Map<string, Note> {
	const map = new Map<string, Note>();
	for (const note of notes) {
		if (map.has(note.name)) {
			warnings.push({
				file: note.rel + '.md',
				message: `duplicate basename "${note.name}" — wikilinks resolve to ${map.get(note.name)!.rel}.md`
			});
		} else {
			map.set(note.name, note);
		}
	}
	return map;
}

const IMAGE_EXTENSIONS = new Set([
	'.png',
	'.jpg',
	'.jpeg',
	'.gif',
	'.webp',
	'.avif',
	'.svg',
	'.bmp',
	'.ico'
]);

function findVaultFile(target: string, fromDir: string): string | undefined {
	// Obsidian resolves by: exact vault path, path relative to the note, then basename
	const candidates = [target, path.posix.join(fromDir, target)];
	for (const candidate of candidates) {
		if (existsSync(path.join(VAULT_DIR, candidate))) return path.posix.normalize(candidate);
	}
	const base = path.posix.basename(target);
	const stack: string[] = [''];
	while (stack.length > 0) {
		const dir = stack.pop()!;
		const abs = path.join(VAULT_DIR, dir, base);
		if (existsSync(abs)) return path.posix.normalize(path.posix.join(dir, base));
		if (dir.split('/').length > 3) continue;
		readdirSync(path.join(VAULT_DIR, dir), { withFileTypes: true })
			.filter((entry) => entry.isDirectory() && !entry.name.startsWith('.'))
			.forEach((entry) => stack.push(path.posix.join(dir, entry.name)));
	}
	return undefined;
}

function uploadsUrlFor(section: string, filename: string): string {
	return path.posix.join('uploads', section || '', filename);
}

function copyToUploads(vaultFile: string, section: string): string {
	const filename = path.posix.basename(vaultFile);
	const destDir = path.join(UPLOADS_DIR, section);
	mkdirSync(destDir, { recursive: true });
	cpSync(path.join(VAULT_DIR, vaultFile), path.join(destDir, filename));
	return uploadsUrlFor(section, filename);
}

function transformBody(note: Note, notes: Note[], config: SvelteConfig): string {
	const { trailingSlash, slug } = config;
	const byNameMap = byName(notes);
	// Served URL is /<routePath> with trailing slash only when kit trailingSlash is
	// 'always'. The browser's "current directory" for relative links is that URL
	// with the page's own name stripped (or the dir itself for dir-style serving):
	//   'always'  → base dir = routePath          (ai/basics/  → from 'ai/basics')
	//   otherwise → base dir = routePath minus page name (ai/basics → from 'ai')
	const pageIsDir = trailingSlash === 'always';
	const fromBase = pageIsDir ? path.posix.join(note.dir, note.name) : note.dir;
	const toBase = (to: string) => {
		const rel = path.posix.relative(fromBase, to);
		return rel === '' ? '.' : rel;
	};

	const resolveHref = (target: string): string | undefined => {
		const [rawPath, rawFragment] = target.split('#');
		const fragment = rawFragment ? `#${slug(rawFragment)}` : '';
		const base = path.posix.basename(rawPath);
		const targetNote = byNameMap.get(base);
		if (targetNote && targetNote.rel === note.rel) {
			errors.push({
				file: note.rel + '.md',
				message: `embeds of the current note are not supported: [${target}]`
			});
			return undefined;
		}
		if (targetNote) {
			return `${toBase(path.posix.join(targetNote.dir, targetNote.name))}${fragment}`;
		}
		// Not a note — maybe media referenced with a path
		const vaultFile = findVaultFile(rawPath, note.dir);
		if (vaultFile && IMAGE_EXTENSIONS.has(path.extname(vaultFile).toLowerCase())) {
			const uploadsUrl = copyToUploads(vaultFile, note.dir);
			return `${toBase(uploadsUrl)}${fragment}`;
		}
		return undefined;
	};

	let body = note.body;

	// Obsidian callouts: "> [!note] Title" → plain blockquote
	body = body.replace(
		/(^|\n)(\s*>)\s*\[!(?:note|tip|info|question|warning|danger|example|quote|details|faq|abstract)\][+-]?\s*/g,
		'$1$2 '
	);

	// Embeds and wikilinks: ![[x]] / [[x]] / [[x|alias]] / [[x#heading]]
	body = body.replace(/(!?)\[\[(?:[^]|(?!\]\)).)+?\]\]/g, (whole, bang: string) => {
		const inner = whole.slice(bang.length + 2, -2);
		const [rawTarget, alias] = inner.split('|');
		const target = rawTarget.trim();
		const label = (alias ?? target.split('#').pop() ?? target).trim();
		const href = resolveHref(rawTarget);
		if (!href) {
			errors.push({
				file: note.rel + '.md',
				message: `cannot resolve ${bang ? 'embed' : 'wikilink'} [${inner.trim()}]`
			});
			return whole; // leave intact so the failure is visible in the rendered page
		}
		return `${bang}[${label}](${href})`;
	});

	// Plain markdown images pointing at vault files
	body = body.replace(
		/(!\[[^\]]*\])\(([^)\s]+)(?:\s+"[^"]*")?\)/g,
		(whole, label: string, src: string) => {
			if (/^[a-z]+:\/\//i.test(src) || src.startsWith('data:')) return whole; // external / inline
			const vaultFile = findVaultFile(src, note.dir);
			if (!vaultFile || !IMAGE_EXTENSIONS.has(path.extname(vaultFile).toLowerCase())) return whole;
			const uploadsUrl = copyToUploads(vaultFile, note.dir);
			return `${label}(${toBase(uploadsUrl)})`;
		}
	);

	return body;
}

function escapeHtml(value: string): string {
	return value
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}

function generatePage(note: Note, markdown: string): string {
	const lines: string[] = [MARKER, '<script lang="ts">', '</script>', ''];
	if (note.title || note.description) {
		lines.push('<svelte:head>');
		if (note.title) lines.push(`\t<title>${escapeHtml(note.title)}</title>`);
		if (note.description)
			lines.push(`\t<meta name="description" content="${escapeHtml(note.description)}" />`);
		lines.push('</svelte:head>', '');
	}
	lines.push(markdown.endsWith('\n') || markdown === '' ? markdown : markdown + '\n');
	return lines.join('\n');
}

function generateToc(section: string, sectionNotes: Note[]): string {
	const items = [...sectionNotes].sort((a, b) => a.order - b.order || a.name.localeCompare(b.name));
	const lines: string[] = [
		`// GENERATED by \`npm run content:sync\` from the Obsidian vault (content/${section || ''}). Do not edit.`,
		"import type { AppTypes } from '$app/types';",
		'',
		"type TocPath = ReturnType<AppTypes['Path']>; // union of all real routes (generated by SvelteKit)",
		'',
		'export type TocItem = { path: TocPath; label: string };',
		'',
		'export const tocItems: TocItem[] = [',
		...items.map((note, index) => {
			const line = `\t{ path: '${path.posix.join(section, note.name)}' satisfies TocPath, label: '${note.title.replace(/'/g, `\\'`)}' }`;
			return index === items.length - 1 ? line : `${line},`;
		}),
		'];'
	];
	return lines.join('\n') + '\n';
}

function deleteStalePages(expected: Set<string>): string[] {
	const deleted: string[] = [];
	if (!existsSync(ROUTES_DIR)) return deleted;
	const walk = (abs: string): void => {
		for (const entry of readdirSync(abs, { withFileTypes: true })) {
			if (!entry.isDirectory()) continue;
			const page = path.join(abs, entry.name, '+page.svx');
			if (existsSync(page)) {
				const content = readFileSync(page, 'utf8');
				if (content.startsWith(MARKER) && !expected.has(path.resolve(page))) {
					rmSync(page);
					const dir = path.dirname(page);
					if (readdirSync(dir).length === 0) rmSync(dir, { recursive: true });
					deleted.push(path.relative(process.cwd(), page));
				}
			}
			walk(path.join(abs, entry.name));
		}
	};
	walk(ROUTES_DIR);
	return deleted;
}

async function run(): Promise<void> {
	// reset per-run state (watch mode reuses the process)
	errors.length = 0;
	warnings.length = 0;
	skipped.length = 0;

	const config = await loadSvelteConfig();
	const notes = collectNotes();
	if (notes.length === 0) {
		console.log(
			`[content:sync] no notes found in ${path.relative(process.cwd(), VAULT_DIR)}/ — nothing to do`
		);
		return;
	}

	const transformed = new Map<string, string>();
	for (const note of notes) transformed.set(note.rel, transformBody(note, notes, config));

	if (errors.length > 0) {
		for (const error of errors) console.error(`  ✖ ${error.file}: ${error.message}`);
		throw new Error(
			`${errors.length} transform error(s) — nothing was written. Fix the notes above and re-run.`
		);
	}

	const expected = new Set<string>();
	for (const note of notes) {
		const dest = path.join(ROUTES_DIR, note.dir, note.name, '+page.svx');
		mkdirSync(path.dirname(dest), { recursive: true });
		writeFileSync(dest, generatePage(note, transformed.get(note.rel)!));
		expected.add(dest);
		console.log(`  ✔ ${path.relative(process.cwd(), dest)} ← content/${note.rel}`);
	}

	// TOC per section (sections = vault dirs that contain notes)
	const sections = new Set(notes.map((note) => note.dir));
	for (const section of sections) {
		const tocPath = path.join(ROUTES_DIR, section, 'toc.ts');
		mkdirSync(path.dirname(tocPath), { recursive: true });
		writeFileSync(
			tocPath,
			generateToc(
				section,
				notes.filter((note) => note.dir === section)
			)
		);
		console.log(
			`  ✔ ${path.relative(process.cwd(), tocPath)} ← ${notes.filter((n) => n.dir === section).length} note(s)`
		);
	}

	for (const deleted of deleteStalePages(expected)) console.log(`  ✖ deleted stale ${deleted}`);
	for (const warning of warnings) console.warn(`  ⚠ ${warning.file}: ${warning.message}`);
	for (const note of skipped) console.log(`  ○ skipped ${note} (publish: false)`);
	console.log(`[content:sync] done — ${notes.length} note(s) published, ${skipped.length} skipped`);
}

if (process.argv.includes('--watch')) {
	void run().catch((error: Error) => console.error(error.message));
	let timer: NodeJS.Timeout | undefined;
	const queue = new Set<string>();
	const watcher = import('node:fs').then(({ default: fs }) =>
		fs.watch(VAULT_DIR, { recursive: true }, (_event, filename) => {
			if (!filename || !filename.toLowerCase().endsWith('.md')) return;
			queue.add(filename);
			clearTimeout(timer);
			timer = setTimeout(() => {
				queue.clear();
				void run().catch((error: Error) => console.error(error.message));
			}, 300);
		})
	);
	void watcher;
	console.log(
		`[content:watch] watching ${path.relative(process.cwd(), VAULT_DIR)}/ — ctrl+c to stop`
	);
} else {
	void (async () => {
		try {
			await run();
		} catch (error) {
			console.error((error as Error).message);
			process.exitCode = 1;
		}
	})();
}
